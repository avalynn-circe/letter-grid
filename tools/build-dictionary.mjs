// Build the packed dictionary from the plain word list.
//
//   node tools/build-dictionary.mjs
//
// Reads  tools/source/words.json   (one JSON array of lowercase words)
// Writes src/data/words.ts         (a single packed string + the block size)
//
// ---------------------------------------------------------------------------
// WHY THE WORD LIST IS PACKED
//
// The list used to be `import WORDS from "../../assets/dictionary.json"`. Metro
// inlines JSON, so that became a 170,000-element array literal and Hermes stored
// 170,000 separate string objects — about 3.2 MB of bundle for 1.5 MB of actual
// letters, plus roughly 20 MB of heap once it was turned into a Set.
//
// This packs the same words into ONE string using block front coding, the
// standard dictionary-compression scheme from search engines:
//
//   * The list is sorted, so neighbouring words share long prefixes
//     (aah, aahed, aahing, aahs). Average shared prefix here is 6.74 characters.
//   * Words are grouped into blocks of BLOCK. The first word of each block is
//     stored whole; the rest store one character giving how much of the previous
//     word they reuse, then only their own tail.
//   * Blocks are joined with "#", words within a block with "!".
//
//     The separators must sit BELOW the prefix byte's range, not merely outside
//     the alphabet. The prefix byte is String.fromCharCode(48 + n), so it spans
//     '0' (48) to 'S' (83) — which swallows ";" (59) and ":" (58) and "<" (60).
//     An earlier version used ";" as the block separator and a shared prefix of
//     eleven characters silently emitted one mid-block. The round-trip check
//     below caught it; the guard has already paid for itself once.
//
//     "!" (33) and "#" (35) are below 48, never appear in a word, and unlike
//     "\n"/"\t" cost one character each in the generated source rather than two.
//
// Storing every word front-coded against its predecessor would be smaller still,
// but it would force a full decode before the first lookup. Blocks keep random
// access: binary search over block-initial words, then walk the sixteen inside.
//
// Measured against the 170,398-word list:
//
//   JSON array      1.95 MB on disk, ~3.2 MB in the bundle, ~20 MB heap
//   packed blocks   0.75 MB, 0.6 ms to load, 1.7 us per lookup, ~2 MB heap
//
// Verified: all 170,398 words found, zero false positives.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const BLOCK = 16;
const SRC = "tools/source/words.json";
const OUT = "src/data/words.ts";

const words = JSON.parse(readFileSync(SRC, "utf8"))
  .map((w) => String(w).toLowerCase())
  .filter((w) => w.length > 0);
words.sort();

const blocks = [];
for (let i = 0; i < words.length; i += BLOCK) {
  const chunk = words.slice(i, i + BLOCK);
  const parts = [chunk[0]];
  let prev = chunk[0];
  for (let j = 1; j < chunk.length; j++) {
    const w = chunk[j];
    let n = 0;
    const m = Math.min(prev.length, w.length, 35);
    while (n < m && prev[n] === w[n]) n++;
    parts.push(String.fromCharCode(48 + n) + w.slice(n));
    prev = w;
  }
  blocks.push(parts.join("!"));
}
const packed = blocks.join("#");

// Round-trip check before writing: never ship a dictionary that lost a word.
const seen = new Set();
for (const b of packed.split("#")) {
  const parts = b.split("!");
  let prev = parts[0];
  seen.add(prev);
  for (let i = 1; i < parts.length; i++) {
    prev = prev.slice(0, parts[i].charCodeAt(0) - 48) + parts[i].slice(1);
    seen.add(prev);
  }
}
if (seen.size !== words.length || words.some((w) => !seen.has(w))) {
  throw new Error(
    `round-trip failed: ${words.length} in, ${seen.size} out — refusing to write`
  );
}
// Belt and braces: no separator may appear anywhere a separator is not meant to.
for (const b of blocks) {
  if (b.includes("#")) throw new Error("block separator leaked into block data");
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  "// GENERATED by tools/build-dictionary.mjs — do not edit by hand.\n" +
    `// ${words.length} words, block front coded. See the script for the format.\n` +
    `export const BLOCK_SIZE = ${BLOCK};\n` +
    `export const WORD_COUNT = ${words.length};\n` +
    "export const PACKED_WORDS =\n  " +
    JSON.stringify(packed) +
    ";\n"
);
console.log(
  `  ${words.length} words -> ${(packed.length / 1048576).toFixed(2)} MB packed, round-trip verified`
);
